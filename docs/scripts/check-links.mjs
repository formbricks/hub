#!/usr/bin/env node
/**
 * Fails if the built site contains an internal link or asset reference that does
 * not resolve to something in dist/.
 *
 * Written because two rounds of hand-checking missed real 404s, each time
 * because the check was narrower than the problem:
 *
 *   1. only `href` was checked, so a broken image `src` shipped;
 *   2. only root-absolute paths were checked — anything not starting with "/"
 *      was assumed fine — so nine relative `./hub-*` links shipped. Those are
 *      the subtle ones: `./hub-powerbi` on `/guides/hub-databricks/` resolves to
 *      `/guides/hub-databricks/hub-powerbi/`, not `/guides/hub-powerbi/`, and
 *      Starlight canonicalises to trailing slashes so it breaks every time.
 *
 * So this resolves every reference against the page it appears on, exactly as a
 * browser would, and checks href and src alike.
 *
 * Usage: node scripts/check-links.mjs [distDir]   (default: dist)
 */
import { readFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const dist = process.argv[2] ?? "dist";

if (!existsSync(dist)) {
  console.error(`No build output at ${dist}/ — run \`pnpm build\` first.`);
  process.exit(1);
}

/** Every .html file in the build, with the URL it is served at. */
function* htmlFiles(dir) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) yield* htmlFiles(full);
    else if (entry.endsWith(".html")) yield full;
  }
}

const pageUrl = (file) => {
  const rel = "/" + relative(dist, file).split("\\").join("/");
  return rel.endsWith("/index.html") ? rel.slice(0, -"index.html".length) : rel;
};

/** Does this site-absolute path exist in the build? */
const exists = (p) => {
  const clean = p.split("#")[0].split("?")[0].replace(/^\/+/, "");
  if (clean === "") return existsSync(join(dist, "index.html"));
  return (
    existsSync(join(dist, clean, "index.html")) || existsSync(join(dist, clean))
  );
};

// Generated by the framework and verified by the build itself; checking them
// only adds noise.
const ignored = (u) => u.startsWith("/_astro") || u.startsWith("/pagefind");

const external = (u) =>
  /^(https?:|mailto:|tel:|data:|javascript:|#|\/\/)/i.test(u);

const broken = [];
let pages = 0;
let checked = 0;

for (const file of htmlFiles(dist)) {
  pages++;
  const from = pageUrl(file);
  const html = readFileSync(file, "utf8");
  const refs = new Set();
  for (const m of html.matchAll(/\b(?:href|src)="([^"]+)"/g)) refs.add(m[1]);

  for (const raw of refs) {
    if (external(raw) || ignored(raw)) continue;
    // Resolve against the page's own URL, which is what a browser does and what
    // makes "./foo" on a trailing-slash URL different from "/foo".
    const resolved = new URL(raw, `https://x${from}`).pathname;
    if (ignored(resolved)) continue;
    checked++;
    if (!exists(resolved)) broken.push({ from, raw, resolved });
  }
}

console.log(`Checked ${checked} internal references across ${pages} pages.`);

if (broken.length) {
  console.error(`\n${broken.length} broken reference(s):\n`);
  for (const { from, raw, resolved } of broken.sort((a, b) =>
    a.from.localeCompare(b.from),
  )) {
    console.error(`  ${from}\n    ${raw}  ->  ${resolved}  (404)`);
  }
  console.error(
    "\nUse root-absolute links (/guides/foo/) for pages — relative ones",
  );
  console.error("resolve against the current URL and break when a page moves.");
  process.exit(1);
}

console.log("No broken internal references.");
